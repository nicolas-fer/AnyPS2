// "0000 01" → (0b000001, 6).
struct Bits {
    std::uint32_t code = 0;
    unsigned len = 0;
};
constexpr Bits parse(const char* s) {
    Bits b;
    for (; *s; ++s) {
        if (*s == ' ') continue;
        b.code = (b.code << 1) | static_cast<std::uint32_t>(*s == '1');
        ++b.len;
    }
    return b;
}

// Tabela de consulta direta: os `width` primeiros bits do fluxo indexam a
// entrada (comprimento 0 = código inválido).
template <typename Entry>
struct Lookup {
    unsigned width = 0;
    std::vector<Entry> entries;
    void put(Bits b, Entry e) {
        const unsigned free = width - b.len;
        const std::uint32_t first = b.code << free;
        for (std::uint32_t i = 0; i < (1u << free); ++i) entries[first + i] = e;
    }
    const Entry& at(std::uint32_t bits) const { return entries[bits >> (32 - width)]; }
};

template <std::size_t N>
Lookup<Vlc> build(const VlcCode (&codes)[N]) {
    Lookup<Vlc> t;
    for (const VlcCode& c : codes) t.width = std::max(t.width, parse(c.code).len);
    t.entries.resize(std::size_t{1} << t.width);
    for (const VlcCode& c : codes) {
        const Bits b = parse(c.code);
        t.put(b, Vlc{c.value, b.len});
    }
    return t;
}

template <std::size_t N>
Lookup<Dct> buildDct(const DctCode (&codes)[N], const char* eob) {
    Lookup<Dct> t;
    t.width = 16;
    t.entries.resize(std::size_t{1} << t.width);
    for (const DctCode& c : codes) {
        const Bits b = parse(c.code);
        t.put(b, Dct{Dct::Coef, static_cast<std::uint8_t>(c.run), static_cast<std::uint8_t>(c.level),
                     static_cast<std::uint8_t>(b.len)});
    }
    const Bits e = parse(eob), x = parse(kDctEscape);
    t.put(e, Dct{Dct::Eob, 0, 0, static_cast<std::uint8_t>(e.len)});
    t.put(x, Dct{Dct::Escape, 0, 0, static_cast<std::uint8_t>(x.len)});
    return t;
}

struct Tables {
    std::array<Lookup<Vlc>, 9> vlc;
    Lookup<Dct> dctZero, dctOne;
    Tables()
        : vlc{build(kMbai),       build(kMbTypeI),  build(kMbTypeP),     build(kMbTypeB),      build(kCbp),
              build(kMotionCode), build(kDmVector), build(kDcSizeLuma), build(kDcSizeChroma)},
          dctZero(buildDct(kDctZero, kDctZeroEob)),
          dctOne(buildDct(kDctOne, kDctOneEob)) {}
};

const Tables& tables() {
    static const Tables t;
    return t;
}

// cos((2x+1)uπ/16) · C(u)/2, com C(0) = 1/√2.
struct IdctBasis {
    double c[8][8];
    IdctBasis() {
        const double pi = std::acos(-1.0);
        for (int x = 0; x < 8; ++x) {
            for (int u = 0; u < 8; ++u) {
                const double cu = u == 0 ? std::sqrt(0.5) : 1.0;
                c[x][u] = cu / 2 * std::cos((2 * x + 1) * u * pi / 16);
            }
        }
    }
};

