Vlc decode(Table table, std::uint32_t bits) {
    return tables().vlc[static_cast<std::size_t>(table)].at(bits);
}

Dct decodeDct(bool tableOne, bool first, std::uint32_t bits) {
    if (first && !tableOne && (bits >> 31)) return Dct{Dct::Coef, 0, 1, 1};
    return (tableOne ? tables().dctOne : tables().dctZero).at(bits);
}

void idct(const std::int32_t (&in)[64], std::int32_t (&out)[64]) {
    static const IdctBasis basis;
    double rows[64];
    // Linhas (frequência horizontal u → x), depois colunas (v → y).
    for (int v = 0; v < 8; ++v) {
        for (int x = 0; x < 8; ++x) {
            double s = 0;
            for (int u = 0; u < 8; ++u) s += basis.c[x][u] * in[v * 8 + u];
            rows[v * 8 + x] = s;
        }
    }
    for (int x = 0; x < 8; ++x) {
        for (int y = 0; y < 8; ++y) {
            double s = 0;
            for (int v = 0; v < 8; ++v) s += basis.c[y][v] * rows[v * 8 + x];
            out[y * 8 + x] = static_cast<std::int32_t>(std::floor(s + 0.5));
        }
    }
}

